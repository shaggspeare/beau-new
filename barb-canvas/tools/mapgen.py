import math, sys
LNG0,LNG1,LAT0 = 30.30,30.70,50.56
KX = 1000/((LNG1-LNG0)*111.32*math.cos(math.radians(50.45)))
def P(lat,lng): return ((lng-LNG0)/(LNG1-LNG0)*1000, (LAT0-lat)*110.57*KX)
def cr_path(pts, closed=False, t=0.5):
    pts=[P(a,b) for a,b in pts]
    n=len(pts)
    if n<2: return ''
    d=f"M{pts[0][0]:.1f},{pts[0][1]:.1f}"
    rng = range(n) if closed else range(n-1)
    for i in rng:
        p0=pts[(i-1)%n] if closed else pts[max(i-1,0)]
        p1=pts[i]; p2=pts[(i+1)%n]
        p3=pts[(i+2)%n] if closed else pts[min(i+2,n-1)]
        c1=(p1[0]+(p2[0]-p0[0])/6*t*2, p1[1]+(p2[1]-p0[1])/6*t*2)
        c2=(p2[0]-(p3[0]-p1[0])/6*t*2, p2[1]-(p3[1]-p1[1])/6*t*2)
        d+=f" C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}"
    if closed: d+=" Z"
    return d
def ellipse(lat,lng,rlat,rlng,n=10):
    return [(lat+rlat*math.sin(2*math.pi*k/n), lng+rlng*math.cos(2*math.pi*k/n)) for k in range(n)]

